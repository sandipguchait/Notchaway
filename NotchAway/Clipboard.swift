import AppKit
import SwiftUI

struct ClipItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable {
        case text, image, files
    }

    enum SmartAction {
        case track(String)
        case map(String)
        case saveCode(String)

        var symbol: String {
            switch self {
            case .track: return "shippingbox.fill"
            case .map: return "map.fill"
            case .saveCode: return "chevron.left.forwardslash.chevron.right"
            }
        }

        var help: String {
            switch self {
            case .track: return "Track package"
            case .map: return "Open in Maps"
            case .saveCode: return "Save code to Notes"
            }
        }
    }

    var id = UUID()
    var kind: Kind
    var text: String?
    var filePaths: [String]?
    var imageFile: String?
    var date = Date()
    var pinned = false
    var sourceApp: String?

    var preview: String {
        switch kind {
        case .text:
            return (text ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
        case .files:
            let names = (filePaths ?? []).map { URL(fileURLWithPath: $0).lastPathComponent }
            return names.joined(separator: ", ")
        case .image:
            return "Image"
        }
    }

    var link: URL? {
        guard kind == .text, let text = text?.trimmingCharacters(in: .whitespacesAndNewlines),
              !text.contains(" "), !text.contains("\n"),
              let url = URL(string: text), let scheme = url.scheme?.lowercased(),
              ["http", "https"].contains(scheme), url.host != nil else { return nil }
        return url
    }

    var email: String? {
        guard kind == .text, let text = text?.trimmingCharacters(in: .whitespacesAndNewlines),
              text.range(of: #"^[A-Z0-9a-z._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$"#, options: .regularExpression) != nil
        else { return nil }
        return text
    }

    var color: NSColor? {
        guard kind == .text, var hex = text?.trimmingCharacters(in: .whitespacesAndNewlines),
              hex.range(of: #"^#?([0-9a-fA-F]{3}|[0-9a-fA-F]{6})$"#, options: .regularExpression) != nil
        else { return nil }
        if hex.hasPrefix("#") { hex.removeFirst() }
        if hex.count == 3 { hex = hex.map { "\($0)\($0)" }.joined() }
        guard let value = UInt32(hex, radix: 16) else { return nil }
        return NSColor(srgbRed: CGFloat((value >> 16) & 0xFF) / 255,
                       green: CGFloat((value >> 8) & 0xFF) / 255,
                       blue: CGFloat(value & 0xFF) / 255,
                       alpha: 1)
    }

    var smartAction: SmartAction? {
        guard kind == .text, let value = text?.trimmingCharacters(in: .whitespacesAndNewlines), !value.isEmpty else {
            return nil
        }
        if value.range(of: #"(?i)^\d{1,6}\s+.+\s(street|st|road|rd|avenue|ave|lane|ln|drive|dr|boulevard|blvd|way)(,.*)?$"#,
                       options: .regularExpression) != nil {
            return .map(value)
        }
        if value.count <= 40, !value.contains(" "),
           value.range(of: #"^[A-Za-z0-9-]{10,40}$"#, options: .regularExpression) != nil,
           value.rangeOfCharacter(from: .decimalDigits) != nil,
           value.rangeOfCharacter(from: .letters) != nil {
            return .track(value)
        }
        let codeMarkers = ["func ", "class ", "struct ", "import ", "const ", "let ", "var ", "def ", "=>", "{", "</"]
        if value.contains("\n"), codeMarkers.contains(where: value.contains) {
            return .saveCode(value)
        }
        return nil
    }

    func isSameContent(as other: ClipItem) -> Bool {
        kind == other.kind && text == other.text && filePaths == other.filePaths && kind != .image
    }
}

@MainActor
final class ClipboardService: ObservableObject {
    @Published private(set) var items: [ClipItem]

    var limit = 60 {
        didSet {
            trim()
            save()
        }
    }

    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let imagesDirectory = AppPaths.directory("Clips")
    private let thumbnails = NSCache<NSString, NSImage>()

    /// Password managers and other apps mark secrets with these types (nspasteboard.org).
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword"
    ]

    init() {
        items = JSONStore.load([ClipItem].self, from: "clipboard.json") ?? []
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
    }

    func copy(_ item: ClipItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.kind {
        case .text:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .files:
            let urls = (item.filePaths ?? []).map { URL(fileURLWithPath: $0) as NSURL }
            pasteboard.writeObjects(urls)
        case .image:
            if let image = image(for: item) { pasteboard.writeObjects([image]) }
        }
        lastChangeCount = pasteboard.changeCount

        if let index = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: index)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].pinned.toggle()
        save()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        removeImageFile(of: item)
        save()
    }

    func clearUnpinned() {
        items.filter { !$0.pinned }.forEach(removeImageFile)
        items.removeAll { !$0.pinned }
        save()
    }

    func image(for item: ClipItem) -> NSImage? {
        guard let name = item.imageFile else { return nil }
        if let cached = thumbnails.object(forKey: name as NSString) { return cached }
        guard let image = NSImage(contentsOf: imagesDirectory.appendingPathComponent(name)) else { return nil }
        thumbnails.setObject(image, forKey: name as NSString)
        return image
    }

    // MARK: Internals

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        let source = NSWorkspace.shared.frontmostApplication?.localizedName

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            insert(ClipItem(kind: .files, filePaths: urls.map(\.path), sourceApp: source))
            return
        }

        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            insert(ClipItem(kind: .text, text: text, sourceApp: source))
            return
        }

        if let image = NSImage(pasteboard: pasteboard), let png = image.pngData() {
            let name = UUID().uuidString + ".png"
            do {
                try png.write(to: imagesDirectory.appendingPathComponent(name), options: .atomic)
                insert(ClipItem(kind: .image, imageFile: name, sourceApp: source))
            } catch {
                return
            }
        }
    }

    private func insert(_ item: ClipItem) {
        var item = item
        if let index = items.firstIndex(where: { $0.isSameContent(as: item) }) {
            item.pinned = items[index].pinned
            item.id = items[index].id
            items.remove(at: index)
        }
        items.insert(item, at: 0)
        trim()
        save()
    }

    private func trim() {
        var unpinnedCount = 0
        var kept: [ClipItem] = []
        for item in items {
            if item.pinned {
                kept.append(item)
            } else if unpinnedCount < limit {
                unpinnedCount += 1
                kept.append(item)
            } else {
                removeImageFile(of: item)
            }
        }
        if kept.count != items.count { items = kept }
    }

    private func removeImageFile(of item: ClipItem) {
        guard let name = item.imageFile else { return }
        thumbnails.removeObject(forKey: name as NSString)
        try? FileManager.default.removeItem(at: imagesDirectory.appendingPathComponent(name))
    }

    private func save() {
        JSONStore.save(items, to: "clipboard.json")
    }
}

struct ClipboardTabView: View {
    @EnvironmentObject private var clipboard: ClipboardService
    @State private var search = ""
    @State private var copiedID: UUID?

    private var filtered: [ClipItem] {
        let query = search.trimmingCharacters(in: .whitespaces).lowercased()
        let sorted = clipboard.items.filter(\.pinned) + clipboard.items.filter { !$0.pinned }
        guard !query.isEmpty else { return sorted }
        return sorted.filter { $0.preview.lowercased().contains(query) || ($0.sourceApp?.lowercased().contains(query) ?? false) }
    }

    var body: some View {
        VStack(spacing: 8) {
            HStack(spacing: 8) {
                HStack(spacing: 6) {
                    Image(systemName: "magnifyingglass").foregroundStyle(.secondary)
                    TextField("Search clipboard", text: $search)
                        .textFieldStyle(.plain)
                }
                .font(.system(size: 12))
                .padding(.horizontal, 10)
                .padding(.vertical, 6)
                .background(LuminousCardSurface(shape: Capsule(), accent: LuminousCardTheme.violet))

                Text("\(clipboard.items.count) items")
                    .font(.system(size: 11))
                    .foregroundStyle(.secondary)
                PillButton(title: "Clear", symbol: "trash") { clipboard.clearUnpinned() }
            }

            if filtered.isEmpty {
                EmptyStateView(symbol: "doc.on.clipboard",
                               title: search.isEmpty ? "Clipboard is empty" : "No matches",
                               subtitle: search.isEmpty ? "Everything you copy shows up here. Pin items to keep them forever." : nil)
            } else {
                ScrollView {
                    LazyVStack(spacing: 4) {
                        ForEach(filtered) { item in
                            ClipRow(item: item, isCopied: copiedID == item.id) {
                                clipboard.copy(item)
                                copiedID = item.id
                                Task { @MainActor in
                                    try? await Task.sleep(nanoseconds: 1_200_000_000)
                                    if copiedID == item.id { copiedID = nil }
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}

private struct ClipRow: View {
    let item: ClipItem
    let isCopied: Bool
    let onCopy: () -> Void

    @EnvironmentObject private var clipboard: ClipboardService
    @EnvironmentObject private var notes: NotesService

    var body: some View {
        HStack(spacing: 10) {
            leadingVisual
                .frame(width: 30, height: 30)

            VStack(alignment: .leading, spacing: 2) {
                Text(item.preview)
                    .font(.system(size: 12))
                    .lineLimit(2)
                Text([item.sourceApp, Format.relative(item.date)].compactMap { $0 }.joined(separator: " · "))
                    .font(.system(size: 10))
                    .foregroundStyle(.secondary)
            }
            Spacer(minLength: 4)

            if isCopied {
                Text("Copied")
                    .font(.system(size: 10, weight: .semibold))
                    .foregroundStyle(.green)
            }
            if let action = item.smartAction {
                IslandIconButton(symbol: action.symbol, help: action.help) { perform(action) }
            }
            if let url = item.link {
                IslandIconButton(symbol: "safari", help: "Open link") { NSWorkspace.shared.open(url) }
            } else if let email = item.email, let url = URL(string: "mailto:\(email)") {
                IslandIconButton(symbol: "envelope", help: "Compose email") { NSWorkspace.shared.open(url) }
            } else if item.kind == .files, let first = item.filePaths?.first {
                IslandIconButton(symbol: "folder", help: "Reveal in Finder") {
                    NSWorkspace.shared.activateFileViewerSelecting([URL(fileURLWithPath: first)])
                }
            }
            IslandIconButton(symbol: item.pinned ? "pin.fill" : "pin", isActive: item.pinned, help: "Pin") {
                clipboard.togglePin(item)
            }
            IslandIconButton(symbol: "xmark", help: "Delete") { clipboard.delete(item) }
        }
        .padding(.horizontal, 8)
        .padding(.vertical, 6)
        .background(
            LuminousCardSurface(
                shape: RoundedRectangle(cornerRadius: 12, style: .continuous),
                accent: item.pinned ? LuminousCardTheme.violet : LuminousCardTheme.azure
            )
        )
        .contentShape(Rectangle())
        .onTapGesture(perform: onCopy)
    }

    private func perform(_ action: ClipItem.SmartAction) {
        switch action {
        case .track(let number):
            let query = "track package \(number)".addingPercentEncoding(withAllowedCharacters: .urlQueryAllowed) ?? number
            if let url = URL(string: "https://www.google.com/search?q=\(query)") { NSWorkspace.shared.open(url) }
        case .map(let address):
            let query = address.addingPercentEncoding(withAllowedCharacters: .urlQueryAllowed) ?? address
            if let url = URL(string: "https://maps.apple.com/?q=\(query)") { NSWorkspace.shared.open(url) }
        case .saveCode(let code):
            notes.add(text: "Code Snippet · \(Date().formatted(date: .abbreviated, time: .shortened))\n\n\(code)")
        }
    }

    @ViewBuilder
    private var leadingVisual: some View {
        if let color = item.color {
            Circle().fill(Color(nsColor: color))
                .overlay(Circle().stroke(Color.white.opacity(0.3), lineWidth: 1))
        } else if item.kind == .image, let image = clipboard.image(for: item) {
            Image(nsImage: image)
                .resizable()
                .aspectRatio(contentMode: .fill)
                .clipShape(RoundedRectangle(cornerRadius: 5))
        } else if item.kind == .files, let first = item.filePaths?.first {
            Image(nsImage: NSWorkspace.shared.icon(forFile: first))
                .resizable()
        } else {
            Image(systemName: item.link != nil ? "link" : "text.alignleft")
                .font(.system(size: 13))
                .foregroundStyle(.secondary)
        }
    }
}
